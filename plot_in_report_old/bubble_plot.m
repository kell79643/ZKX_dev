%% =========================
% 11. 局部函数：带偏置中心的 coolwarm
% =========================
function map = coolwarm_centered_biased(N, clim, centerValue)
% 作用：
% 1) 基于 coolwarm 生成分段蓝-白-红色图
% 2) 通过 centerValue 控制“白色中心”位置
% 3) 本例中 centerValue = log10(0.85)
%    因此 1x、1.1x、1.5x 会偏暖，只有 0.6x 明显偏蓝

    if nargin < 1 || isempty(N)
        N = size(get(gcf, 'colormap'), 1);
    end
    if nargin < 2 || isempty(clim)
        clim = caxis;
    end
    if nargin < 3 || isempty(centerValue)
        centerValue = 0;
    end

    baseMap = coolwarm(256);
    baseX = linspace(0, 1, size(baseMap,1));

    v = linspace(clim(1), clim(2), N);
    t = zeros(size(v));

    if centerValue <= clim(1)
        t = 0.5 + 0.5*(v - clim(1)) / (clim(2)-clim(1));
    elseif centerValue >= clim(2)
        t = 0.5*(v - clim(1)) / (clim(2)-clim(1));
    else
        idxBlue = v <= centerValue;
        idxRed  = v > centerValue;

        t(idxBlue) = 0.5 * ...
            (v(idxBlue) - clim(1)) / (centerValue - clim(1));

        t(idxRed) = 0.5 + 0.5 * ...
            (v(idxRed) - centerValue) / (clim(2) - centerValue);
    end

    t = max(0, min(1, t));
    map = interp1(baseX, baseMap, t, 'linear');
    map = max(0, min(1, map));
end

